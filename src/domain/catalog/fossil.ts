/** "Flip a coin. If heads, the Defending Pokémon is now <status>." */
const coinStatus = (status: StatusCondition): AttackEffect => ({
  type: AttackEffectType.ApplyStatus,
  target: AttackTarget.Defender,
  coinFlip: { count: 1, onHeads: status },
});

/** "The Defending Pokémon is now <status>." */
const status = (value: StatusCondition): AttackEffect => ({
  type: AttackEffectType.ApplyStatus,
  target: AttackTarget.Defender,
  status: value,
});

/** "Flip N coins. This attack does X damage times the number of heads." */
const coinDamage = (amount: number, count: number): AttackEffect => ({
  type: AttackEffectType.CoinFlipDamage,
  target: AttackTarget.Defender,
  amount,
  coinFlip: { count, onHeads: "damage" },
});

/** Water Gun: +10 per Water Energy not used to pay the cost, at most +20. */
const waterGun: AttackEffect = {
  type: AttackEffectType.ExtraEnergy,
  target: null,
  extraDamagePerEnergy: 10,
  maxExtraEnergy: 2,
  extraEnergyType: Water,
};

/** "If your opponent has any Benched Pokémon, choose 1 of them and this attack does N damage to it." */
const chooseOneBenched = (amount: number): AttackEffect => ({
  type: AttackEffectType.BenchDamage,
  target: AttackTarget.Defender,
  amount,
  benchTarget: BenchDamageTarget.Opponent,
  maxBenchTargets: 1,
});

/** Selfdestruct: N to every Benched Pokémon (both sides) and M to itself. */
const selfdestruct = (benchDamage: number, selfDamage: number): AttackEffect[] => [
  { type: AttackEffectType.SelfDamage, target: AttackTarget.Self, amount: selfDamage },
  { type: AttackEffectType.BenchDamage, target: AttackTarget.Defender, amount: benchDamage, benchTarget: BenchDamageTarget.Both },
];

/** Leech Life / Absorb: remove damage counters from itself based on the damage done. */
const healFromDamage = (mode: "all" | "halfRoundedUp"): AttackEffect => ({
  type: AttackEffectType.Heal,
  target: AttackTarget.Self,
  healFromDamage: mode,
});


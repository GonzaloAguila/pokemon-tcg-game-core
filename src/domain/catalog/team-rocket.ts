/** "Flip a coin. If heads, the Defending Pokémon is now <status>." */
const coinStatus = (value: StatusCondition): AttackEffect => ({
  type: AttackEffectType.ApplyStatus,
  target: AttackTarget.Defender,
  coinFlip: { count: 1, onHeads: value },
});

/** "The Defending Pokémon is now <status>." */
const status = (value: StatusCondition): AttackEffect => ({
  type: AttackEffectType.ApplyStatus,
  target: AttackTarget.Defender,
  status: value,
});

/** "Flip a coin. If heads, this attack does N damage plus M more damage" (M on heads). */
const coinBonus = (amount: number): AttackEffect => ({
  type: AttackEffectType.CoinFlipDamage,
  target: AttackTarget.Defender,
  amount,
  coinFlip: { count: 1, onHeads: "damage" },
});

/** "Flip a coin. If tails, this attack does nothing." */
const tailsFails: AttackEffect = { type: AttackEffectType.AttackFails, target: null, coinFlip: { count: 1, onTails: "damage" } };

/** "Don't apply Weakness and Resistance for this attack." */
const noWeaknessResistance: AttackEffect = { type: AttackEffectType.IgnoreWeaknessResistance, target: null };

/** "Choose 1 of your opponent's Pokémon. This attack does N damage to that Pokémon (no W/R)." */
const chooseAnyOpponent = (amount: number, extra: Partial<AttackEffect> = {}): AttackEffect => ({
  type: AttackEffectType.ChooseTargetDamage,
  target: AttackTarget.Defender,
  amount,
  targetScope: "opponentAny",
  ...extra,
});

/** Discard N Fire Energy cards attached to the attacker (with a coin: one per heads). */
const discardFire = (coinCountFromFire = false): AttackEffect => ({
  type: AttackEffectType.Discard,
  target: AttackTarget.Self,
  energyType: Fire,
  amount: 1,
  coinFlip: { count: 1, onHeads: "damage" },
  ...(coinCountFromFire && { coinCountFromEnergyType: Fire }),
});

